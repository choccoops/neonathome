// Write the Neon At Home Macros compendium (packs/_source/macros) and its icons (assets/macros):
// one script macro per window, opening it for the selected token's character (or the user's
// own). For the hotbar, Neon Combat Manager's Action HUD, Neon Hub page buttons and active tiles.
import { mkdir, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "packs", "_source", "macros");
const icons = path.join(root, "assets", "macros");
const MODULE_ID = "cpr-neon-at-home";
const id = (s) => createHash("sha256").update(`macro:${s}`).digest("base64").replace(/[^A-Za-z0-9]/g, "").slice(0, 16);

/** Each glyph is SVG drawn in a 512 box, stroked in cyan over the tile. */
const GLYPHS = {
  home: `<path d="M110 250 256 126l146 124M152 222v168h72v-92h64v92h72V222"/>`,
  loadout: `<path d="M178 186h156a30 30 0 0 1 30 30v176H148V216a30 30 0 0 1 30-30zM214 186v-26a42 42 0 0 1 84 0v26M196 270h120v62H196z"/>`,
  deck: `<path d="M176 176h160v160H176zM216 216h80v80h-80zM216 176v-44M296 176v-44M216 336v44M296 336v44M176 216h-44M176 296h-44M336 216h44M336 296h44"/>`,
  bay: `<path d="M116 300l36-90h208l36 90M100 300h312v62H100zM148 362v32M364 362v32"/><circle cx="160" cy="331" r="10"/><circle cx="352" cy="331" r="10"/>`,
  bench: `<circle cx="256" cy="256" r="104"/><circle cx="256" cy="256" r="26"/><path d="M256 112v72M256 328v72M112 256h72M328 256h72"/>`,
  maintenance: `<path d="M318 132a76 76 0 0 0-92 98L130 326a32 32 0 0 0 46 46l96-96a76 76 0 0 0 98-92l-48 48-42-12-12-42z"/>`,
  downtime: `<path d="M150 200h180v120a70 70 0 0 1-70 70h-40a70 70 0 0 1-70-70zM330 228h24a38 38 0 0 1 0 76h-24M200 116c-14 22 14 34 0 56M260 116c-14 22 14 34 0 56"/>`,
  biomonitor: `<path d="M256 384 132 262a72 72 0 0 1 124-82 72 72 0 0 1 124 82L256 384zM112 262h86l26-46 40 92 26-46h110"/>`,
  perks: `<circle cx="256" cy="140" r="34"/><circle cx="160" cy="372" r="34"/><circle cx="352" cy="372" r="34"/><path d="M240 170l-66 172M272 170l66 172M194 372h124"/>`,
  spendIp: `<path d="M148 268l108-100 108 100M148 364l108-100 108 100"/>`,
  dive: `<circle cx="256" cy="128" r="26"/><circle cx="186" cy="256" r="26"/><circle cx="326" cy="256" r="26"/><circle cx="256" cy="384" r="26"/><path d="M242 150l-42 82M270 150l42 82M200 280l42 82M312 280l-42 82"/>`
};

function icon(key) {
  return `<svg width="512" height="512" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- Neon At Home macro icon: ${key}. Generated by tools/gen-macros.mjs. -->
  <path d="M24 24h420l44 44v420H68l-44-44z" fill="#07070b" stroke="#ff2a6d" stroke-width="16"/>
  <path d="M56 452h120" stroke="#f3e600" stroke-width="10"/>
  <g fill="none" stroke="#05d9e8" stroke-width="26" stroke-linecap="round" stroke-linejoin="round">${GLYPHS[key]}</g>
</svg>
`;
}

const MACROS = [
  { key: "home", name: "Home", call: "home.open(who)", what: "the home suite" },
  { key: "loadout", name: "Loadout", call: 'home.open(who, "loadout")', what: "the Loadout tab" },
  { key: "deck", name: "Cyberdeck", call: 'home.open(who, "deck")', what: "the Cyberdeck tab" },
  { key: "bay", name: "Vehicle Bay", call: 'home.open(who, "bay")', what: "the Vehicle Bay tab" },
  { key: "bench", name: "Weaponbench", call: 'home.open(who, "bench")', what: "the Weaponbench tab" },
  { key: "maintenance", name: "Maintenance", call: 'home.open(who, "maintenance")', what: "the Maintenance tab" },
  { key: "downtime", name: "Downtime", call: 'home.open(who, "downtime")', what: "the Downtime tab" },
  { key: "biomonitor", name: "Biomonitor", call: "home.biomonitor(who)", what: "the Biomonitor" },
  { key: "perks", name: "Perk Tree", call: "home.perkTree(who)", what: "the Perk Tree" },
  { key: "spendIp", name: "Spend IP", call: "home.spendIp(who)", what: "Spend IP" },
  { key: "dive", name: "Deep Dive", call: "home.deepDive(who)", what: "the Deep Dive" }
];

const command = (m) => `// Neon At Home: open ${m.what} for the selected token's character (or your own).
// Works from the hotbar, Neon Combat Manager's Action HUD, a Neon Hub page button or an active tile.
const home = game.modules.get("${MODULE_ID}")?.api;
if (!home) return ui.notifications.warn("Neon At Home isn't active in this world.");
const who = (typeof actor !== "undefined" && actor) || (typeof character !== "undefined" && character) || null;
return ${m.call};
`;

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await mkdir(icons, { recursive: true });
let sort = 0;
for (const m of MACROS) {
  await writeFile(path.join(icons, `${m.key}.svg`), icon(m.key));
  const _id = id(m.key);
  const doc = {
    _id,
    _key: `!macros!${_id}`,
    name: `Neon At Home: ${m.name}`,
    type: "script",
    scope: "global",
    img: `modules/${MODULE_ID}/assets/macros/${m.key}.svg`,
    command: command(m),
    folder: null,
    sort: (sort += 100),
    ownership: { default: 0 },
    flags: { [MODULE_ID]: { macro: m.key } }
  };
  await writeFile(path.join(out, `${m.key}_${_id}.json`), `${JSON.stringify(doc, null, 2)}\n`);
}
console.log(`wrote ${MACROS.length} macros`);
